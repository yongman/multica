import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

// Mermaid's published IIFE contains all diagram loaders. Embed it as data,
// never execute it in Hermes and never fetch a runtime from a CDN.
const require = createRequire(import.meta.url);
const runtimePath = path.join(path.dirname(require.resolve("mermaid")), "mermaid.min.js");
const runtime = await readFile(runtimePath, "utf8");
const output = new URL("../lib/markdown/mermaid-runtime.generated.ts", import.meta.url);
await writeFile(output, `// Generated by scripts/prepare-markdown-preview.mjs; do not edit.\nexport default ${JSON.stringify(runtime)};\n`);
